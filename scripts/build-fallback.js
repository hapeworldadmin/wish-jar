import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { PADLET_PAGE_URL } from "../lib/constants.js";
import { parseFeedXml } from "../lib/parseFeed.js";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const xml = readFileSync(join(root, "data", "padlet_feed_sample.xml"), "utf8");
const wishes = parseFeedXml(xml);
const payload = {
  source: "fallback",
  title: "Wishes for ACS & Epseen",
  padletUrl: PADLET_PAGE_URL,
  wishes,
};

const out = join(root, "src", "data", "fallback-wishes.js");
mkdirSync(dirname(out), { recursive: true });
const file = `// Generated by scripts/build-fallback.js from data/padlet_feed_sample.xml.
// Bundled with the site so the jar still opens if the live feed is unreachable.
export const fallbackPayload = ${JSON.stringify(payload, null, 2)};
`;
writeFileSync(out, file);
console.log(`Wrote ${wishes.length} wishes to ${out}`);
